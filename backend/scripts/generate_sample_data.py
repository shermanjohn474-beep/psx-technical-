def build(name: str, sc: dict) -> pd.DataFrame:
    prefix = wander(sc["seed"], sc["start"], sc["legs"], drift=sc["drift"])
    i0, p0 = prefix[-1]
    wp = prefix + [(i0 + i, p0 * r) for i, r in sc["pattern"][1:]]
    n = int(wp[-1][0]) + 1
    noise = 0.004 * np.mean([p for _, p in wp])
    spikes = {i0 + k: v for k, v in sc.get("spikes", {}).items()}
    return make_ohlcv(wp, noise=noise, wick=noise * 1.6, seed=sc["seed"], volume=800_000, volume_spikes=spikes,
                      index=index_ending(n))


def build_intraday(daily: pd.DataFrame, days: int = 30, seed: int = 99) -> pd.DataFrame:
    """15-minute synthetic bars (09:30-15:30 PKT) consistent in scale with the daily series."""
    rng = np.random.default_rng(seed)
    rows = []
    for ts, d in daily.tail(days).iterrows():
        slots = pd.date_range(ts + pd.Timedelta(hours=9, minutes=30), ts + pd.Timedelta(hours=15, minutes=15), freq="15min")
        path = np.linspace(d["open"], d["close"], len(slots) + 1)
        path[1:-1] += rng.normal(0, (d["high"] - d["low"]) * 0.15, len(slots) - 1)
        for k, s in enumerate(slots):
            o, c = path[k], path[k + 1]
            hi = min(d["high"], max(o, c) + abs(rng.normal(0, (d["high"] - d["low"]) * 0.05)))
            lo = max(d["low"], min(o, c) - abs(rng.normal(0, (d["high"] - d["low"]) * 0.05)))
            rows.append((s, o, max(hi, o, c), min(lo, o, c), c, round(d["volume"] / len(slots) * rng.uniform(0.5, 1.5))))
    return pd.DataFrame(rows, columns=["timestamp", "open", "high", "low", "close", "volume"]).set_index("timestamp")


def write(df: pd.DataFrame, sym: str, tf: str, desc: str) -> None:
    path = OUT / f"{sym}_{tf}.csv"
    out = df.reset_index()
    out["timestamp"] = out["timestamp"].astype(str)
    with path.open("w") as fh:
        fh.write("# SYNTHETIC DEMO DATA - NOT REAL PSX PRICES\n")
        out.round(4).to_csv(fh, index=False)
    path.with_suffix(".meta.json").write_text(json.dumps({
        "attribution": "SYNTHETIC DEMO DATA generated by scripts/generate_sample_data.py - NOT real PSX prices.",
        "synthetic": True, "adjusted": True, "notes": [desc]}, indent=2))


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for sym, sc in SCENARIOS.items():
        daily = build(sym, sc)
        write(daily, sym, "1d", sc["desc"])
        if sym == "SYN-FLAG":
            write(build_intraday(daily), sym, "15m", "Synthetic 15-minute bars for intraday demo")
        print(f"{sym}: {len(daily)} daily bars, last close {daily['close'].iloc[-1]:.2f}")


if __name__ == "__main__":
    main()
