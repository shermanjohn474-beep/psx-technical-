END = "2026-10-07"


def index_ending(n: int, end: str = END) -> pd.DatetimeIndex:
    hol = load_holidays()
    days = [d for d in pd.bdate_range(end=end, periods=int(n * 1.1) + 20) if d.date() not in hol][-n:]
    return pd.DatetimeIndex(days, name="timestamp").tz_localize(PKT)


def wander(seed: int, start: float, legs: int, leg_len=(12, 30), amp=0.12, drift=0.0) -> list[tuple[int, float]]:
    rng = np.random.default_rng(seed)
    wp, i, p = [(0, start)], 0, start
    for _ in range(legs):
        i += int(rng.integers(*leg_len))
        p = max(5.0, p * (1 + rng.normal(drift, amp)))
        wp.append((i, p))
    return wp


